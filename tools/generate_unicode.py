#!/usr/bin/env python3
"""Generate offline Zig tables from the official Unicode 17.0.0 UCD.

Usage: python3 tools/generate_unicode.py /path/to/ucd
Required inputs are listed in UNICODE.md. No network or third-party packages.
"""
import argparse
import subprocess
import hashlib
import sys
from pathlib import Path

parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("source", type=Path)
parser.add_argument("--check", action="store_true", help="Verify generated files without writing")
args = parser.parse_args()
source = args.source
root = Path(__file__).resolve().parents[1]
names = ['UnicodeData.txt', 'SpecialCasing.txt', 'DerivedCoreProperties.txt',
         'DerivedNormalizationProps.txt', 'PropList.txt']
rows = {}
for line in (source / names[0]).read_text().splitlines():
    f = line.split(';')
    rows[int(f[0], 16)] = f

def properties(name):
    result = {}
    for line in (source / name).read_text().splitlines():
        line = line.split('#')[0].strip()
        if not line:
            continue
        fields = [s.strip() for s in line.split(';')]
        bounds = fields[0].split('..')
        result.setdefault(fields[1], []).append((int(bounds[0], 16), int(bounds[-1], 16)))
    return result

props = properties(names[2])
norm = properties(names[3])
prop_list = properties(names[4])
excluded = {cp for lo, hi in norm['Full_Composition_Exclusion'] for cp in range(lo, hi + 1)}
case = {}
for cp, f in rows.items():
    low = [int(f[13], 16)] if f[13] else [cp]
    upper = [int(f[12], 16)] if f[12] else [cp]
    if low != [cp] or upper != [cp]:
        case[cp] = [low, upper]
for line in (source / names[1]).read_text().splitlines():
    f = [s.strip() for s in line.split('#')[0].split(';')]
    if len(f) >= 5 and f[0] and not f[4]:
        cp = int(f[0], 16)
        case[cp] = [[int(s, 16) for s in f[1].split()], [int(s, 16) for s in f[3].split()]]

decomp = []
flat = []
compositions = []
for cp, f in sorted(rows.items()):
    if not f[5]:
        continue
    parts = f[5].split()
    compat = parts[0].startswith('<')
    seq = [int(s, 16) for s in parts[1:] if s] if compat else [int(s, 16) for s in parts]
    decomp.append((cp, compat, len(flat), len(seq)))
    flat.extend(seq)
    if not compat and len(seq) == 2 and cp not in excluded:
        compositions.append(((seq[0] << 21) | seq[1], cp))

out = ['// Generated by tools/generate_unicode.py. Unicode 17.0.0; Unicode License v3.',
       'pub const version = "17.0.0";',
       'pub const Case = struct { cp: u21, lower: [3]u21, upper: [3]u21, lower_len: u8, upper_len: u8 };',
       'pub const cases = [_]Case{']
for cp, (low, upper) in sorted(case.items()):
    assert len(low) <= 3 and len(upper) <= 3
    a = ','.join(hex(x) for x in low + [0] * (3 - len(low)))
    b = ','.join(hex(x) for x in upper + [0] * (3 - len(upper)))
    out.append(f'.{{ .cp={cp}, .lower=.{{{a}}}, .upper=.{{{b}}}, .lower_len={len(low)}, .upper_len={len(upper)} }},')
out += ['};', 'pub const Decomposition = struct { cp: u21, compat: bool, offset: u16, len: u8 };',
        'pub const decompositions = [_]Decomposition{']
for cp, compat, offset, length in decomp:
    out.append(f'.{{ .cp={cp}, .compat={str(compat).lower()}, .offset={offset}, .len={length} }},')
out += ['};', 'pub const decomposition_data = [_]u21{']
out.extend(','.join(str(cp) for cp in flat[i:i+24]) + ',' for i in range(0, len(flat), 24))
out += ['};', 'pub const Composition = struct { key: u42, cp: u21 };', 'pub const compositions = [_]Composition{']
out.extend(f'.{{ .key={key}, .cp={cp} }},' for key, cp in sorted(compositions))
out += ['};', 'pub const Combining = struct { cp: u21, value: u8 };', 'pub const combining = [_]Combining{']
out.extend(f'.{{ .cp={cp}, .value={f[3]} }},' for cp, f in sorted(rows.items()) if int(f[3]))
out += ['};', 'pub const Range = struct { first: u21, last: u21 };']
for symbol, ranges in [('cased', props['Cased']), ('case_ignorable', props['Case_Ignorable']),
                       ('soft_dotted', prop_list['Soft_Dotted'])]:
    out.append(f'pub const {symbol} = [_]Range{{')
    out.extend(f'.{{ .first={lo}, .last={hi} }},' for lo, hi in sorted(ranges))
    out.append('};')
(root / 'src' / 'unicode').mkdir(exist_ok=True)
generated = subprocess.run(['zig', 'fmt', '--stdin'], input='\n'.join(out) + '\n', text=True, capture_output=True, check=True).stdout
# Validate the fixed recursive-decomposition buffer and table offset widths.
seqs = {cp: flat[offset:offset+length] for cp, compat, offset, length in decomp}
def expansion(cp, active=()):
    assert cp not in active, 'cyclic Unicode decomposition'
    if 0xac00 <= cp < 0xac00 + 11172:
        return 3
    return sum(expansion(child, active + (cp,)) for child in seqs[cp]) if cp in seqs else 1
assert max(expansion(cp) for cp in seqs) <= 18
assert len(flat) < 65536
assert all(length <= 255 for cp, compat, offset, length in decomp)
def output(path, text):
    if args.check:
        if path.read_text() != text:
            raise SystemExit('Generated file differs: ' + str(path))
    else:
        path.write_text(text)
output(root / 'src' / 'unicode' / 'data.zig', generated)
manifest = ['Unicode version: 17.0.0', 'Source: https://www.unicode.org/Public/17.0.0/ucd/', 'SHA-256:']
manifest += [hashlib.sha256((source / n).read_bytes()).hexdigest() + '  ' + n for n in names]
output(root / 'src' / 'unicode' / 'SOURCES.txt', '\n'.join(manifest) + '\n')
